create or replace function public.forum_posts_reset_likes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.likes_count := 0;
  return new;
end;
$$;

drop trigger if exists forum_posts_reset_likes on public.forum_posts;
create trigger forum_posts_reset_likes
  before insert on public.forum_posts
  for each row execute function public.forum_posts_reset_likes();

create or replace function public.forum_likes_sync_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    update public.forum_posts set likes_count = likes_count + 1 where id = new.post_id;
  elsif tg_op = 'DELETE' then
    update public.forum_posts set likes_count = greatest(likes_count - 1, 0) where id = old.post_id;
  end if;
  return null;
end;
$$;

revoke execute on function public.forum_likes_sync_count() from public, anon, authenticated;

drop trigger if exists forum_likes_sync_count on public.forum_likes;
create trigger forum_likes_sync_count
  after insert or delete on public.forum_likes
  for each row execute function public.forum_likes_sync_count();

