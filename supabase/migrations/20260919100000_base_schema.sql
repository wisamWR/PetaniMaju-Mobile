-- ─── Profiles ──────────────────────────────────────────────────────────────
-- Dibuat otomatis saat register (trigger handle_new_user) dari user_metadata.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nama text,
  username text,
  avatar_url text,
  telepon text,
  alamat text,
  kabupaten text,
  provinsi text,
  kecamatan text,
  jenis_tanaman text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

-- Nama & avatar penulis forum perlu terbaca oleh user lain yang login.
drop policy if exists "profiles_select_authenticated" on public.profiles;
create policy "profiles_select_authenticated" on public.profiles
  for select to authenticated using (true);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
  for insert to authenticated with check ((select auth.uid()) = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  insert into public.profiles (
    id, nama, username, telepon, kabupaten, provinsi, kecamatan, jenis_tanaman
  ) values (
    new.id,
    coalesce(meta ->> 'nama', meta ->> 'full_name'),
    meta ->> 'username',
    meta ->> 'telepon',
    meta ->> 'kabupaten',
    meta ->> 'provinsi',
    meta ->> 'kecamatan',
    meta ->> 'jenis_tanaman'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke execute on function public.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Buat profil untuk user yang sudah terdaftar sebelum trigger ada.
insert into public.profiles (id, nama, username, telepon, kabupaten, provinsi, kecamatan, jenis_tanaman)
select
  u.id,
  coalesce(u.raw_user_meta_data ->> 'nama', u.raw_user_meta_data ->> 'full_name'),
  u.raw_user_meta_data ->> 'username',
  u.raw_user_meta_data ->> 'telepon',
  u.raw_user_meta_data ->> 'kabupaten',
  u.raw_user_meta_data ->> 'provinsi',
  u.raw_user_meta_data ->> 'kecamatan',
  u.raw_user_meta_data ->> 'jenis_tanaman'
from auth.users u
on conflict (id) do nothing;

